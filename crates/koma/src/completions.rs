//! Shell completion scripts for the `koma` binary.
//!
//! `koma` takes eight flags and no subcommands, so the scripts are static
//! strings rather than generated from a table. `cli::usage()` and these scripts
//! are kept in sync by `tests::completions_cover_every_flag`.

/// Bash completion script.
pub const BASH: &str = r#"# bash completion for koma — generated by `koma completions bash`.
# Install: koma completions bash | sudo tee /usr/share/bash-completion/completions/koma >/dev/null
_koma() {
    local cur="${COMP_WORDS[COMP_CWORD]}"
    local opts="--tty --winit --headless-check --session --spawn --config -c --help -h --version -V"
    COMPREPLY=($(compgen -W "$opts" -- "$cur"))
}
complete -F _koma koma
"#;

/// Zsh completion script.
pub const ZSH: &str = r#"#compdef koma
# zsh completion for koma — generated by `koma completions zsh`.
# Install: koma completions zsh | sudo tee /usr/share/zsh/site-functions/_koma >/dev/null
_arguments -s \
  '--tty[Run on a Linux VT through libseat, udev and DRM/KMS]' \
  '--winit[Run nested in a window inside an existing Wayland/X11 session]' \
  '--headless-check[Print a version/state-machine check and exit]' \
  '--session[Act as the login session]' \
  '--spawn[COMMAND to spawn once the compositor is ready]:command:_command_names' \
  '(-c --config)'{-c,--config}'[Use PATH instead of XDG config]:path:_files' \
  '(-h --help)'{-h,--help}'[Print help]' \
  '(-V --version)'{-V,--version}'[Print version]'
"#;

/// Fish completion script.
pub const FISH: &str = r#"# fish completion for koma — generated by `koma completions fish`.
# Install: koma completions fish > ~/.config/fish/completions/koma.fish
complete -c koma -l tty -d 'Run on a Linux VT through libseat, udev and DRM/KMS'
complete -c koma -l winit -d 'Run nested in a window inside an existing Wayland/X11 session'
complete -c koma -l headless-check -d 'Print a version/state-machine check and exit'
complete -c koma -l session -d 'Act as the login session'
complete -c koma -l spawn -r -d 'COMMAND to spawn once the compositor is ready'
complete -c koma -s c -l config -r -F -d 'Use PATH instead of XDG config'
complete -c koma -s h -l help -d 'Print help'
complete -c koma -s V -l version -d 'Print version'
"#;

/// Returns the script for a shell name accepted by `koma completions <shell>`.
#[must_use]
pub fn render(shell: &str) -> Option<&'static str> {
    match shell {
        "bash" => Some(BASH),
        "zsh" => Some(ZSH),
        "fish" => Some(FISH),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const FLAGS: &[&str] = &[
        "tty",
        "winit",
        "headless-check",
        "session",
        "spawn",
        "config",
        "help",
        "version",
    ];

    #[test]
    fn completions_cover_every_flag() {
        let usage = crate::cli::usage();
        for flag in FLAGS {
            let long = format!("--{flag}");
            assert!(usage.contains(&long), "usage lost {long}");
            assert!(BASH.contains(&long), "bash script lost {long}");
            assert!(ZSH.contains(&long), "zsh script lost {long}");
            assert!(
                FISH.contains(&format!("-l {flag}")),
                "fish script lost -l {flag}"
            );
        }
        for script in [BASH, ZSH, FISH] {
            assert!(
                script.contains("koma"),
                "completion script lost the binary name"
            );
        }
    }

    #[test]
    fn unknown_shell_is_rejected() {
        assert!(render("powershell").is_none());
        assert!(render("fish").is_some());
    }
}
