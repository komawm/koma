//! Shell completion scripts for the `koma` binary.
//!
//! `koma` takes eight aggregate flags plus the `init`, `completions` and `mcp`
//! subcommands, so the scripts are static strings rather than generated from a
//! table. `cli::usage()` and these scripts are kept in sync by
//! `tests::completions_cover_every_flag`.

/// Bash completion script.
pub const BASH: &str = r#"# bash completion for koma — generated by `koma completions bash`.
# Install: koma completions bash | sudo tee /usr/share/bash-completion/completions/koma >/dev/null
_koma() {
    local cur="${COMP_WORDS[COMP_CWORD]}"
    local prev="${COMP_WORDS[COMP_CWORD-1]}"
    local opts="--tty --winit --headless-check --session --spawn --config -c --help -h --version -V"
    local subopts="--unset --print-tools --auto-mint-admin"
    case "$prev" in
        init) COMPREPLY=($(compgen -W "bash zsh fish nushell" -- "$cur")); return ;;
        completions) COMPREPLY=($(compgen -W "bash zsh fish" -- "$cur")); return ;;
    esac
    if [[ "$cur" == -* ]]; then
        COMPREPLY=($(compgen -W "$opts $subopts" -- "$cur"))
    else
        COMPREPLY=($(compgen -W "completions init mcp" -- "$cur") $(compgen -f -- "$cur"))
    fi
}
complete -F _koma koma
"#;

/// Zsh completion script.
pub const ZSH: &str = r#"#compdef koma
# zsh completion for koma — generated by `koma completions zsh`.
# Install: koma completions zsh | sudo tee /usr/share/zsh/site-functions/_koma >/dev/null
_arguments -s \
  '--tty[Run on a Linux VT through libseat, udev and DRM/KMS]' \
  '--winit[Run nested in a window inside an existing Wayland/X11 session]' \
  '--headless-check[Print a version/state-machine check and exit]' \
  '--session[Act as the login session]' \
  '--spawn[COMMAND to spawn once the compositor is ready]:command:_command_names' \
  '(-c --config)'{-c,--config}'[Use PATH instead of XDG config]:path:_files' \
  '--unset[Remove the live session environment variables]' \
  '--print-tools[Dump the MCP tool schemas and exit]' \
  '--auto-mint-admin[Mint an admin token locally for MCP development]' \
  '(-h --help)'{-h,--help}'[Print help]' \
  '(-V --version)'{-V,--version}'[Print version]' \
  '1:command:(completions init mcp)' \
  '2:argument:(bash zsh fish nushell)'
"#;

/// Fish completion script.
pub const FISH: &str = r#"# fish completion for koma — generated by `koma completions fish`.
# Install: koma completions fish > ~/.config/fish/completions/koma.fish
complete -c koma -l tty -d 'Run on a Linux VT through libseat, udev and DRM/KMS'
complete -c koma -l winit -d 'Run nested in a window inside an existing Wayland/X11 session'
complete -c koma -l headless-check -d 'Print a version/state-machine check and exit'
complete -c koma -l session -d 'Act as the login session'
complete -c koma -l spawn -r -d 'COMMAND to spawn once the compositor is ready'
complete -c koma -s c -l config -r -F -d 'Use PATH instead of XDG config'
complete -c koma -l unset -d 'Remove the live session environment variables'
complete -c koma -l print-tools -d 'Dump the MCP tool schemas and exit'
complete -c koma -l auto-mint-admin -d 'Mint an admin token locally for MCP development'
complete -c koma -s h -l help -d 'Print help'
complete -c koma -s V -l version -d 'Print version'
complete -c koma -n __fish_use_subcommand -a completions -d 'Print a shell completion script and exit'
complete -c koma -n __fish_use_subcommand -a init -d 'Print the live session environment for a shell'
complete -c koma -n __fish_use_subcommand -a mcp -d 'Run the stdio Model Context Protocol server'
complete -c koma -n '__fish_seen_subcommand_from init' -a 'bash zsh fish nushell'
complete -c koma -n '__fish_seen_subcommand_from completions' -a 'bash zsh fish'
"#;

/// Returns the script for a shell name accepted by `koma completions <shell>`.
#[must_use]
pub fn render(shell: &str) -> Option<&'static str> {
    match shell {
        "bash" => Some(BASH),
        "zsh" => Some(ZSH),
        "fish" => Some(FISH),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const FLAGS: &[&str] = &[
        "tty",
        "winit",
        "headless-check",
        "session",
        "spawn",
        "config",
        "unset",
        "print-tools",
        "auto-mint-admin",
        "help",
        "version",
    ];

    #[test]
    fn completions_cover_every_flag_and_subcommand() {
        let usage = crate::cli::usage();
        for flag in FLAGS {
            let long = format!("--{flag}");
            assert!(usage.contains(&long), "usage lost {long}");
            assert!(BASH.contains(&long), "bash script lost {long}");
            assert!(ZSH.contains(&long), "zsh script lost {long}");
            assert!(
                FISH.contains(&format!("-l {flag}")),
                "fish script lost -l {flag}"
            );
        }
        for subcommand in ["completions", "init", "mcp"] {
            assert!(
                usage.contains(subcommand),
                "usage lost the {subcommand} subcommand"
            );
            assert!(
                BASH.contains(subcommand),
                "bash script lost the {subcommand} subcommand"
            );
            assert!(
                ZSH.contains(subcommand),
                "zsh script lost the {subcommand} subcommand"
            );
            assert!(
                FISH.contains(subcommand),
                "fish script lost the {subcommand} subcommand"
            );
        }
        for shell in ["bash", "zsh", "fish", "nushell"] {
            assert!(
                BASH.contains(shell) && ZSH.contains(shell) && FISH.contains(shell),
                "completion scripts lost the {shell} shell"
            );
        }
        for script in [BASH, ZSH, FISH] {
            assert!(
                script.contains("koma"),
                "completion script lost the binary name"
            );
            assert!(
                script.contains("completions"),
                "completion script lost the completions subcommand"
            );
        }
    }

    #[test]
    fn unknown_shell_is_rejected() {
        assert!(render("powershell").is_none());
        assert!(render("fish").is_some());
    }
}
